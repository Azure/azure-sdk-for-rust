//! The generated spec catalog: a human-readable index of every specified behavior.
//!
//! The catalog lives next to this crate as `CATALOG.md` and `catalog.json`. The
//! spec binary checks that both are current. Regenerate them with:
//!
//! ```text
//! AZURE_COSMOS_SPEC_UPDATE_CATALOG=1 cargo test -p cosspec --test spec -- catalog
//! ```

use crate::runner::{specs, SpecDescriptor};
use libtest_mimic::Failed;
use serde::Serialize;
use std::{fmt::Write, path::PathBuf};

/// When `1`, the catalog trial rewrites the catalog instead of checking it.
pub const UPDATE_ENV: &str = "AZURE_COSMOS_SPEC_UPDATE_CATALOG";

#[derive(Serialize)]
struct Entry {
    id: String,
    summary: &'static str,
    service_profiles: Vec<&'static str>,
    requires: Vec<&'static str>,
    resources: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    known_issue: Option<String>,
    source: String,
}

fn source(spec: &SpecDescriptor) -> String {
    let file = spec.file.replace('\\', "/");
    match file.find("tests/") {
        Some(start) => file[start..].to_owned(),
        None => file,
    }
}

fn entries() -> Vec<Entry> {
    specs()
        .into_iter()
        .map(|spec| Entry {
            id: spec.id(),
            summary: spec.summary,
            service_profiles: spec.service_profiles.iter().map(|p| p.name()).collect(),
            requires: spec.requires.iter().map(|c| c.name()).collect(),
            resources: spec
                .params
                .iter()
                .map(|param| match param.profile {
                    Some(profile) => format!("{}({})", param.kind.name(), profile().name),
                    None => param.kind.name().to_owned(),
                })
                .collect(),
            known_issue: spec.known_issue.as_ref().map(|issue| {
                if issue.profiles.is_empty() {
                    issue.reason.to_owned()
                } else {
                    let profiles: Vec<_> = issue.profiles.iter().map(|p| p.name()).collect();
                    format!("{} ({})", issue.reason, profiles.join(", "))
                }
            }),
            source: source(spec),
        })
        .collect()
}

/// Renders the catalog as Markdown.
pub fn markdown() -> String {
    let mut out = String::from(
        "<!-- Generated by cosspec. Do not edit. -->\n\n# Cosmos DB SDK spec catalog\n\n\
         | Spec | Behavior | Service profiles | Requires | Resources |\n\
         | --- | --- | --- | --- | --- |\n",
    );
    let entries = entries();
    for entry in &entries {
        let join = |values: &[String]| {
            if values.is_empty() {
                "-".to_owned()
            } else {
                values.join(", ")
            }
        };
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            entry.id,
            entry.summary.replace('|', "\\|"),
            join(
                &entry
                    .service_profiles
                    .iter()
                    .map(|s| s.to_string())
                    .collect::<Vec<_>>()
            ),
            join(
                &entry
                    .requires
                    .iter()
                    .map(|s| s.to_string())
                    .collect::<Vec<_>>()
            ),
            join(&entry.resources),
        );
    }
    let known: Vec<_> = entries
        .iter()
        .filter_map(|e| e.known_issue.as_ref().map(|reason| (&e.id, reason)))
        .collect();
    if !known.is_empty() {
        out.push_str("\n## Known issues\n\nThe SDK does not meet these specs yet.\n\n");
        for (id, reason) in known {
            let _ = writeln!(out, "- `{id}`: {reason}");
        }
    }
    out
}

/// Renders the catalog as JSON.
pub fn json() -> String {
    let mut out = serde_json::to_string_pretty(&entries()).expect("catalog serializes");
    out.push('\n');
    out
}

pub(crate) fn check_or_update() -> Result<(), Failed> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let update = std::env::var(UPDATE_ENV).as_deref() == Ok("1");
    for (file, expected) in [("CATALOG.md", markdown()), ("catalog.json", json())] {
        let path = root.join(file);
        if update {
            std::fs::write(&path, expected).map_err(|e| Failed::from(e.to_string()))?;
            continue;
        }
        let actual = std::fs::read_to_string(&path)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        if actual != expected {
            return Err(format!(
                "{} is out of date; rerun with {UPDATE_ENV}=1 and commit the result",
                path.display()
            )
            .into());
        }
    }
    Ok(())
}

/// The name of the catalog check in test output.
pub(crate) const TEST_NAME: &str = "catalog::up_to_date";
