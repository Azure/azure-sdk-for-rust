/// Every spec in the binary, registered by `#[spec_test]`.
#[distributed_slice]
pub static SPECS: [SpecDescriptor];

/// Restricts the run to a comma-separated list of service profiles.
pub const PROFILES_ENV: &str = "AZURE_COSMOS_SPEC_PROFILES";

/// When `1`, a spec that needs a capability the backend lacks fails instead of
/// being skipped.
pub const STRICT_ENV: &str = "AZURE_COSMOS_SPEC_STRICT";

/// A future returned by a registered spec.
pub type SpecFuture = Pin<Box<dyn Future<Output = SpecResult>>>;

/// Static metadata for one spec, generated by `#[spec_test]`.
#[derive(Debug)]
pub struct SpecDescriptor {
    /// The function name.
    pub function: &'static str,
    /// The function's `module_path!()`.
    pub module: &'static str,
    /// An explicit stable ID, if the spec set one.
    pub id: Option<&'static str>,
    /// The first paragraph of the function's doc comment.
    pub summary: &'static str,
    /// The source file.
    pub file: &'static str,
    /// The source line.
    pub line: u32,
    /// The service profiles the spec runs under.
    pub service_profiles: &'static [ServiceProfile],
    /// Capabilities the spec declared.
    pub requires: &'static [Capability],
    /// Why the SDK does not meet this spec yet, if it doesn't.
    pub known_issue: Option<KnownIssue>,
    /// The spec's parameters.
    pub params: &'static [ParamDescriptor],
    /// Injects parameters and runs the spec.
    pub run: fn(Arc<SpecContext>) -> SpecFuture,
}

/// A spec the SDK does not meet yet.
#[derive(Debug)]
pub struct KnownIssue {
    /// Why the spec fails today.
    pub reason: &'static str,
    /// The affected service profiles; empty means all of them.
    pub profiles: &'static [ServiceProfile],
}

impl KnownIssue {
    /// Returns `true` if the issue affects `profile`.
    pub fn affects(&self, profile: ServiceProfile) -> bool {
        self.profiles.is_empty() || self.profiles.contains(&profile)
    }
}

/// Static metadata for one spec parameter.
#[derive(Debug)]
pub struct ParamDescriptor {
    /// The parameter name.
    pub name: &'static str,
    /// The injected resource kind.
    pub kind: ParamKind,
    /// The container profile from `#[profile(...)]`.
    pub profile: Option<fn() -> ContainerProfile>,
}

impl SpecDescriptor {
    /// The stable spec ID, for example `query.continuation_survives_split`.
    ///
    /// Defaults to the module path below the test crate root plus the function name.
    pub fn id(&self) -> String {
        if let Some(id) = self.id {
            return id.to_owned();
        }
        let mut parts: Vec<&str> = self.module.split("::").skip(1).collect();
        parts.push(self.function);
        parts.join(".")
    }

    /// The test name for one backend and service profile, for example
    /// `spec::query::continuation_survives_split[inmemory.SingleRegion]`.
    pub fn test_name(&self, backend: &str, profile: ServiceProfile) -> String {
        format!("{}::{}[{backend}.{profile}]", self.module, self.function)
    }
}

/// Every registered spec, sorted by ID.
pub fn specs() -> Vec<&'static SpecDescriptor> {
    let mut specs: Vec<_> = SPECS.iter().collect();
    specs.sort_by_key(|spec| spec.id());
    specs
}

fn runtime() -> &'static tokio::runtime::Runtime {
    static RUNTIME: OnceLock<tokio::runtime::Runtime> = OnceLock::new();
    RUNTIME.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .enable_all()
            .build()
            .expect("tokio runtime")
    })
}

fn selected_profiles() -> Option<Vec<ServiceProfile>> {
    let value = std::env::var(PROFILES_ENV).ok()?;
    Some(
        value
            .split(',')
            .map(str::trim)
            .filter(|name| !name.is_empty())
            .map(|name| {
                ServiceProfile::from_name(name)
                    .unwrap_or_else(|| panic!("unknown service profile '{name}' in {PROFILES_ENV}"))
            })
            .collect(),
    )
}

/// Runs every registered spec. Call this from a `harness = false` test's `main`.
///
/// Accepts the usual libtest arguments plus:
///
/// * `--config <path>`: the TOML [`SpecConfig`] naming the backends and service
///   profiles to run. Defaults to [`SpecConfig::default`].
/// * `--no-cleanup`: keep every database and container the run creates, and
///   skip deleting leftovers from earlier runs.
/// * `--results-dir <dir>`: the directory to write one result file per executed
///   trial to. Defaults to `<target>/cosspec-results/<run-id>`.
/// * `--no-prune`: keep every earlier run in `<target>/cosspec-results`. By
///   default, a run that writes results there keeps only the newest ten runs.
///   A custom `--results-dir` is never pruned.
///
/// Results print as a tree: backend, then spec, then service profile.
pub fn main() {
    let exit = |e: &dyn std::fmt::Display| -> ! {
        eprintln!("error: {e}");
        std::process::exit(2);
    };
    let harness = HarnessArgs::parse(std::env::args_os()).unwrap_or_else(|e| exit(&e));
    let config = match &harness.config {
        Some(path) => SpecConfig::load(path).unwrap_or_else(|e| exit(&e)),
        None => SpecConfig::default(),
    };
    let backends = config.backends().unwrap_or_else(|e| exit(&e));
    let args = Arguments::from_iter(harness.libtest);
    let prune_root =
        (harness.results_dir.is_none() && !harness.no_prune).then(results::default_root);
    let results_dir = harness
        .results_dir
        .unwrap_or_else(|| results::default_dir(pool::run_id()));
    results::set_dir(results_dir);
    if harness.no_cleanup {
        pool::disable_cleanup();
    }
    results::install_panic_hook();
    let strict = std::env::var(STRICT_ENV).as_deref() == Ok("1");
    let only = selected_profiles();

    let specs = specs();
    let mut jobs = Vec::new();
    let mut manifest = Manifest::new(
        pool::run_id(),
        std::env::args().skip(1).collect(),
        pool::cleanup(),
    );
    for backend in &backends {
        let profiles: Vec<_> = backend
            .profiles()
            .into_iter()
            .filter(|profile| only.as_ref().is_none_or(|only| only.contains(profile)))
            .collect();
        manifest.add_backend(backend.as_ref(), &profiles);
        for &spec in &specs {
            for &profile in profiles
                .iter()
                .filter(|profile| spec.service_profiles.contains(profile))
            {
                let (job, entry) = job(backend, spec, profile, strict);
                jobs.push((job, entry));
            }
        }
    }

    let list_only = args.list;
    let jobs = if list_only {
        jobs.into_iter().map(|(job, _)| job).collect()
    } else {
        let mut tracked = Vec::with_capacity(jobs.len());
        for (job, entry) in jobs {
            if !console::is_selected(&args, &job) {
                tracked.push(job);
                continue;
            }
            let index = manifest.add_trial(entry);
            tracked.push(track(job, index));
        }
        if let Some(dir) = results::dir() {
            manifest::begin(dir.to_owned(), manifest);
        }
        tracked
    };
    let passed = console::run(&args, jobs);
    manifest::finish();
    match runtime().block_on(pool::close_all()) {
        Ok(kept) if !kept.is_empty() && !list_only => {
            eprintln!(
                "--no-cleanup: kept the pooled databases below; result files list every resource."
            );
            for (backend, profile, database) in kept {
                eprintln!("  {backend}.{profile}: {database}");
            }
        }
        Ok(_) => {}
        Err(e) => eprintln!("warning: failed to delete pooled spec databases: {e}"),
    }
    if let Some(dir) = results::dir().filter(|dir| !list_only && dir.exists()) {
        eprintln!("spec results: {}", dir.display());
        if let Some(root) = prune_root {
            if let Err(e) = results::prune(&root, results::KEEP_RUNS) {
                eprintln!("warning: failed to prune {}: {e}", root.display());
            }
        }
    }
    std::process::exit(if passed { 0 } else { 101 });
}

/// Wraps `job` so its outcome is recorded in the run manifest.
fn track(job: Job, index: usize) -> Job {
    let run = job.run;
    Job {
        run: Box::new(move || {
            let start = Instant::now();
            let result = std::panic::catch_unwind(AssertUnwindSafe(run));
            let duration_ms = start.elapsed().as_secs_f64() * 1000.0;
            let recorded = match &result {
                Ok(Ok(())) => Ok(()),
                Ok(Err(failed)) => Err(failed.message().unwrap_or_default().to_owned()),
                Err(payload) => Err(panic_message(payload.as_ref())),
            };
            manifest::record(index, &recorded, duration_ms);
            result.unwrap_or_else(|payload| std::panic::resume_unwind(payload))
        }),
        ..job
    }
}

fn job(
    backend: &Arc<dyn Backend>,
    spec: &'static SpecDescriptor,
    profile: ServiceProfile,
    strict: bool,
) -> (Job, TrialEntry) {
    let name = spec.test_name(backend.name(), profile);
    let place = Place {
        backend: backend.name().to_owned(),
        spec: spec.id(),
        profile: profile.name().to_owned(),
    };
    let available = backend.capabilities(profile);
    let missing: Vec<_> = spec
        .requires
        .iter()
        .filter(|capability| !available.contains(capability))
        .map(|capability| capability.name())
        .collect();
    if !missing.is_empty() {
        let reason = format!("{} lacks {}", backend.name(), missing.join(", "));
        let entry = TrialEntry::new(
            spec,
            backend.as_ref(),
            profile,
            if strict { Planned::Run } else { Planned::Skip },
            Some(reason.clone()),
        );
        let backend = backend.clone();
        let message = format!("skipped: {reason}");
        return (
            Job {
                name,
                place,
                ignore: (!strict).then_some(Ignore::Skip(reason)),
                run: Box::new(move || {
                    let mut record = TrialRecord::start(spec, profile, backend.as_ref());
                    record.error = Some(message.into());
                    finish_trial(record)
                }),
            },
            entry,
        );
    }

    let known_issue = spec
        .known_issue
        .as_ref()
        .filter(|issue| issue.affects(profile));
    let entry = TrialEntry::new(
        spec,
        backend.as_ref(),
        profile,
        if known_issue.is_some() {
            Planned::KnownIssue
        } else {
            Planned::Run
        },
        known_issue.map(|issue| issue.reason.to_owned()),
    );
    let backend = backend.clone();
    let job = Job {
        name,
        place,
        ignore: known_issue.is_some().then_some(Ignore::KnownIssue),
        run: Box::new(move || finish_trial(runtime().block_on(run_spec(backend, spec, profile)))),
    };
    (job, entry)
}

/// Writes the trial's result file and converts it to a libtest outcome.
fn finish_trial(record: TrialRecord) -> Result<(), Failed> {
    let result = record.result();
    let written = match results::dir() {
        Some(dir) => record.write(dir),
        None => Ok(()),
    };
    result.map_err(Failed::from)?;
    written.map_err(|e| Failed::from(e.to_string()))
}

async fn run_spec(
    backend: Arc<dyn Backend>,
    spec: &'static SpecDescriptor,
    profile: ServiceProfile,
) -> TrialRecord {
    let mut record = TrialRecord::start(spec, profile, backend.as_ref());
    let cell = pool::cell(&backend, profile).await;
    record.phase("pool", record.started);
    let cell = match cell {
        Ok(cell) => cell,
        Err(e) => {
            record.error = Some(e);
            return record;
        }
    };
    let ctx = Arc::new(SpecContext::new(cell, spec, profile));
    results::take_panic();
    let body = Instant::now();
    let outcome = AssertUnwindSafe((spec.run)(ctx.clone()))
        .catch_unwind()
        .await;
    record.phase("body", body);
    match outcome {
        Ok(result) => record.error = result.err(),
        Err(payload) => {
            record.panic = Some(
                results::take_panic().unwrap_or_else(|| results::PanicRecord {
                    message: panic_message(payload.as_ref()),
                    location: None,
                    backtrace: String::new(),
                }),
            )
        }
    }
    let teardown = Instant::now();
    record.teardown_error = ctx.finish().await.err();
    record.phase("teardown", teardown);
    record.resources = ctx.resources();
    record.http = ctx.recording();
    record
}

pub(crate) fn panic_message(payload: &(dyn std::any::Any + Send)) -> String {
    payload
        .downcast_ref::<String>()
        .cloned()
        .or_else(|| payload.downcast_ref::<&str>().map(|s| (*s).to_owned()))
        .unwrap_or_else(|| "spec panicked".to_owned())
}
