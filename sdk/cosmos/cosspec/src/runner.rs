//! Spec registration and the `libtest-mimic` runner.

use crate::{
    backend::{self, Backend},
    catalog,
    context::{ParamKind, SpecContext},
    pool,
    profiles::ContainerProfile,
    Capability, ServiceProfile, SpecResult,
};
use futures::FutureExt;
use libtest_mimic::{Arguments, Failed, Trial};
use linkme::distributed_slice;
use std::{
    future::Future,
    panic::AssertUnwindSafe,
    pin::Pin,
    sync::{Arc, OnceLock},
};

/// Every spec in the binary, registered by `#[spec_test]`.
#[distributed_slice]
pub static SPECS: [SpecDescriptor];

/// Restricts the run to a comma-separated list of service profiles.
pub const PROFILES_ENV: &str = "AZURE_COSMOS_SPEC_PROFILES";

/// When `1`, a spec that needs a capability the backend lacks fails instead of
/// being skipped.
pub const STRICT_ENV: &str = "AZURE_COSMOS_SPEC_STRICT";

/// A future returned by a registered spec.
pub type SpecFuture = Pin<Box<dyn Future<Output = SpecResult>>>;

/// Static metadata for one spec, generated by `#[spec_test]`.
#[derive(Debug)]
pub struct SpecDescriptor {
    /// The function name.
    pub function: &'static str,
    /// The function's `module_path!()`.
    pub module: &'static str,
    /// An explicit stable ID, if the spec set one.
    pub id: Option<&'static str>,
    /// The first paragraph of the function's doc comment.
    pub summary: &'static str,
    /// The source file.
    pub file: &'static str,
    /// The source line.
    pub line: u32,
    /// The service profiles the spec runs under.
    pub service_profiles: &'static [ServiceProfile],
    /// Capabilities the spec declared.
    pub requires: &'static [Capability],
    /// Why the SDK does not meet this spec yet, if it doesn't.
    pub known_issue: Option<KnownIssue>,
    /// The spec's parameters.
    pub params: &'static [ParamDescriptor],
    /// Injects parameters and runs the spec.
    pub run: fn(Arc<SpecContext>) -> SpecFuture,
}

/// A spec the SDK does not meet yet.
#[derive(Debug)]
pub struct KnownIssue {
    /// Why the spec fails today.
    pub reason: &'static str,
    /// The affected service profiles; empty means all of them.
    pub profiles: &'static [ServiceProfile],
}

impl KnownIssue {
    /// Returns `true` if the issue affects `profile`.
    pub fn affects(&self, profile: ServiceProfile) -> bool {
        self.profiles.is_empty() || self.profiles.contains(&profile)
    }
}

/// Static metadata for one spec parameter.
#[derive(Debug)]
pub struct ParamDescriptor {
    /// The parameter name.
    pub name: &'static str,
    /// The injected resource kind.
    pub kind: ParamKind,
    /// The container profile from `#[profile(...)]`.
    pub profile: Option<fn() -> ContainerProfile>,
}

impl SpecDescriptor {
    /// The stable spec ID, for example `query.continuation_survives_split`.
    ///
    /// Defaults to the module path below the test crate root plus the function name.
    pub fn id(&self) -> String {
        if let Some(id) = self.id {
            return id.to_owned();
        }
        let mut parts: Vec<&str> = self.module.split("::").skip(1).collect();
        parts.push(self.function);
        parts.join(".")
    }

    /// The test name for one service profile, for example
    /// `spec::query::continuation_survives_split[SingleRegion]`.
    pub fn test_name(&self, profile: ServiceProfile) -> String {
        format!("{}::{}[{profile}]", self.module, self.function)
    }
}

/// Every registered spec, sorted by ID.
pub fn specs() -> Vec<&'static SpecDescriptor> {
    let mut specs: Vec<_> = SPECS.iter().collect();
    specs.sort_by_key(|spec| spec.id());
    specs
}

fn runtime() -> &'static tokio::runtime::Runtime {
    static RUNTIME: OnceLock<tokio::runtime::Runtime> = OnceLock::new();
    RUNTIME.get_or_init(|| {
        tokio::runtime::Builder::new_multi_thread()
            .enable_all()
            .build()
            .expect("tokio runtime")
    })
}

fn selected_profiles() -> Option<Vec<ServiceProfile>> {
    let value = std::env::var(PROFILES_ENV).ok()?;
    Some(
        value
            .split(',')
            .map(str::trim)
            .filter(|name| !name.is_empty())
            .map(|name| {
                ServiceProfile::from_name(name)
                    .unwrap_or_else(|| panic!("unknown service profile '{name}' in {PROFILES_ENV}"))
            })
            .collect(),
    )
}

/// Runs every registered spec. Call this from a `harness = false` test's `main`.
pub fn main() {
    let args = Arguments::from_args();
    let backend = backend::selected().unwrap_or_else(|e| panic!("{e}"));
    let strict = std::env::var(STRICT_ENV).as_deref() == Ok("1");
    let only = selected_profiles();

    let mut trials = vec![catalog::trial()];
    for spec in specs() {
        for &profile in spec.service_profiles {
            if only.as_ref().is_some_and(|only| !only.contains(&profile)) {
                continue;
            }
            trials.push(trial(&backend, spec, profile, strict));
        }
    }

    let conclusion = libtest_mimic::run(&args, trials);
    if let Err(e) = runtime().block_on(pool::close_all()) {
        eprintln!("warning: failed to delete pooled spec databases: {e}");
    }
    conclusion.exit();
}

fn trial(
    backend: &Arc<dyn Backend>,
    spec: &'static SpecDescriptor,
    profile: ServiceProfile,
    strict: bool,
) -> Trial {
    let name = spec.test_name(profile);
    let available = if backend.supports(profile) {
        backend.capabilities(profile)
    } else {
        Vec::new()
    };
    let missing: Vec<_> = spec
        .requires
        .iter()
        .filter(|capability| !available.contains(capability))
        .map(|capability| capability.name())
        .collect();
    let unsupported = !backend.supports(profile);
    if unsupported || !missing.is_empty() {
        let reason = if unsupported {
            format!("{} cannot provide {profile}", backend.name())
        } else {
            format!("{} lacks {}", backend.name(), missing.join(", "))
        };
        let trial = Trial::test(name, move || {
            Err(Failed::from(format!("skipped: {reason}")))
        });
        return if strict {
            trial
        } else {
            trial.with_ignored_flag(true).with_kind("skip")
        };
    }

    let backend = backend.clone();
    let trial = Trial::test(name, move || {
        runtime()
            .block_on(run_spec(backend, spec, profile))
            .map_err(|e| Failed::from(e.to_string()))
    });
    if spec
        .known_issue
        .as_ref()
        .is_some_and(|issue| issue.affects(profile))
    {
        trial.with_ignored_flag(true).with_kind("known-issue")
    } else {
        trial
    }
}

async fn run_spec(
    backend: Arc<dyn Backend>,
    spec: &'static SpecDescriptor,
    profile: ServiceProfile,
) -> SpecResult {
    let cell = pool::cell(&backend, profile).await?;
    let ctx = Arc::new(SpecContext::new(cell, spec, profile));
    let outcome = AssertUnwindSafe((spec.run)(ctx.clone()))
        .catch_unwind()
        .await;
    let teardown = ctx.finish().await;
    match outcome {
        Ok(result) => result.and(teardown),
        Err(panic) => {
            let message = panic
                .downcast_ref::<String>()
                .cloned()
                .or_else(|| panic.downcast_ref::<&str>().map(|s| (*s).to_owned()))
                .unwrap_or_else(|| "spec panicked".to_owned());
            Err(message.into())
        }
    }
}
